// Builds src/data/geo.json (projected map shapes, from public/mapas) and src/generated.ts (which optional files exist).
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const pub = (...p) => path.join(root, 'public', ...p);
const K = 1000; // world = 256*K units, keeps 3 decimals precise even when zoomed into one district
const proj = (lng, lat) => { const s = Math.sin((lat * Math.PI) / 180); return [((lng + 180) / 360) * 256 * K, (0.5 - Math.log((1 + s) / (1 - s)) / (4 * Math.PI)) * 256 * K]; };
const shape = ({ properties: p, geometry: g }) => {
  const parts = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  const box = [Infinity, Infinity, -Infinity, -Infinity];
  let area = 0, cx = 0, cy = 0; // outer rings only (shoelace)
  parts.forEach((poly) => { const pts = poly[0].map(([a, b]) => proj(a, b)); for (let i = 0; i < pts.length - 1; i++) { const [x0, y0] = pts[i], [x1, y1] = pts[i + 1], cr = x0 * y1 - x1 * y0; area += cr / 2; cx += (x0 + x1) * cr; cy += (y0 + y1) * cr; } });
  const d = parts.map((poly) => poly.map((ring) => 'M' + ring.map(([lng, lat]) => {
    const [x, y] = proj(lng, lat);
    box[0] = Math.min(box[0], x); box[1] = Math.min(box[1], y); box[2] = Math.max(box[2], x); box[3] = Math.max(box[3], y);
    return `${x.toFixed(3)} ${y.toFixed(3)}`;
  }).join('L') + 'Z').join('')).join('');
  const cen = area ? [cx / (6 * area), cy / (6 * area)] : proj(p.l[0], p.l[1]);
  area = Math.abs(area);
  return { c: p.c, n: p.n, d, box, area, cen, compact: area / ((box[2] - box[0]) * (box[3] - box[1])), label: proj(p.l[0], p.l[1]) };
};
const feats = (f) => JSON.parse(fs.readFileSync(pub('mapas', f), 'utf8')).features;
const provinces = feats('provincias.json').map(shape);
const cantons = feats('cantones.json').filter((f) => f.properties.p === 'CR3').map(shape);
const districts = feats('distritos-CR3.json').filter((f) => f.properties.p === 'CR301').map(shape);
const plotDistrict = districts.reduce((a, b) => (b.area * b.compact > a.area * a.compact ? b : a)).c;
fs.mkdirSync(path.join(root, 'src/data'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/data/geo.json'), JSON.stringify({ provinces, cantons, districts, plotDistrict }));
const has = (...p) => fs.existsSync(pub(...p));
const voice = ['voz.m4a', 'voz.mp3', 'voz.wav'].find((f) => has('audio', f)) ?? null;
fs.writeFileSync(path.join(root, 'src/generated.ts'), `// Auto-generated by scripts/prep.mjs (runs on dev/render). Do not edit.\nexport const HAS_FOOTAGE = ${has('footage', 'app-uso.mp4')};\nexport const VOICE_FILE: string | null = ${JSON.stringify(voice && 'audio/' + voice)};\nexport const HAS_AUDIO = ${has('audio', 'music.wav')};\n`);
console.log('prep ok · plot district', plotDistrict, '· voice', voice, '· footage', has('footage', 'app-uso.mp4'));
