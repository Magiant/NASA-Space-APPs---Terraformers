type Ampliar<T> = T extends (...a: infer A) => infer R
  ? (...a: A) => R
  : T extends string
    ? string
    : T extends readonly (infer U)[]
      ? T extends [unknown, unknown, unknown] ? [string, string, string] : Ampliar<U>[]
      : { [K in keyof T]: Ampliar<T[K]> };

